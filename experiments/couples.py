#!/usr/bin/env python3
"""Couples and houses: who courted whom, who said yes, and what got built.

    python experiments/couples.py <run_id> [<run_id> ...]

For each run, told couple by couple:

- every proposal, with its day, who asked whom, how fond they were, and the
  answer (yes, no, or none before it lapsed)
- every marriage, where the couple lived, and whether they waited for a house
- every house the crafters built, the day it was finished, and for whom
- how often the courtship and building instructions were chosen, and how
  often they ranked but were refused
- where the proposal ranked when a villager's sweetheart was near, since only
  the top few that can be carried out are chosen among
- the fondest eligible pair at the last dawn

It reports no statistics over temperament or genes. Mate choice by
temperament is selection, which is the behavioural-genetics paper's to
report (SPECIFICATION section 2.7b).

Writes results/couples.json and .md, or into another directory given
with --out, for runs that are not the paper's.
"""

from __future__ import annotations

import collections
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
RESULTS = ROOT / "results"
DECISIONS = ("family-seek-sweetheart", "family-propose", "family-accept-proposal",
             "family-decline-prefer-another", "family-decline-not-ready",
             "crafter-fell-timber", "crafter-start-house", "crafter-build-house")


def day_of(t: int) -> int:
    return (6 * 60 + t * 10) // (24 * 60)


def analyse(run_id: str) -> dict:
    run = RUNS / run_id
    proposals, houses, sites = [], [], []
    married, declined = {}, {}
    chosen, refused = collections.Counter(), collections.Counter()
    last_building, fondest, propose_rank = None, None, collections.Counter()
    with open(run / "events.jsonl", encoding="utf-8") as f:
        for line in f:
            e = json.loads(line)
            kind = e["type"]
            if kind == "proposed":
                proposals.append({"day": day_of(e["t"]), "t": e["t"], "asker": e["asker"],
                                  "asked": e["asked"], "affinity": e["affinity"]})
            elif kind == "married":
                married[(e["asker"], e["asked"])] = e
            elif kind == "declined":
                declined[(e["asker"], e["asked"], e["t"])] = e
            elif kind == "place_added" and e["place"]["kind"] == "site":
                sites.append({"day": day_of(e["t"]), "by": e.get("by")})
            elif kind == "house_built":
                houses.append({"day": day_of(e["t"]), "place": e["place"],
                               "couple": e.get("couple")})
            elif kind == "courtship":
                fondest = {"day": day_of(e["t"]), "pair": e["fondest"][0]}
            elif kind == "building":
                last_building = {"day": day_of(e["t"]), "timber": round(e["timber"], 1),
                                 "progress": round(e["progress"], 1), "waiting": e["waiting"]}
            elif kind == "decision" and e.get("character") != "world":
                if "sweetheart_near" in (e.get("tags") or []):
                    ids = [c["id"] for c in e.get("retrieved") or []]
                    rank = ids.index("family-propose") + 1 if "family-propose" in ids else None
                    propose_rank[rank or "not retrieved"] += 1
                if e.get("chosen") in DECISIONS:
                    chosen[e["chosen"]] += 1
                for r in e.get("refused") or []:
                    if r in DECISIONS:
                        refused[r] += 1

    for p in proposals:
        m = married.get((p["asker"], p["asked"]))
        no = [d for (a, b, t), d in declined.items()
              if (a, b) == (p["asker"], p["asked"]) and t >= p["t"]]
        if m is not None and m["t"] >= p["t"]:
            p["answer"], p["home"], p["waited"] = "yes", m["home"], m["waiting"]
        elif no:
            p["answer"] = "no"
        else:
            p["answer"] = "none"
    return {"run": run_id, "proposals": proposals, "marriages": len(married),
            "sites_started": sites, "houses": houses, "building_at_last_dawn": last_building,
            "fondest_at_last_dawn": fondest,
            "propose_rank_with_sweetheart_near": {str(k): v for k, v in sorted(
                propose_rank.items(), key=lambda kv: (isinstance(kv[0], str), kv[0]))},
            "chosen": dict(chosen), "refused": dict(refused)}


def markdown(results: list[dict]) -> str:
    out = ["# Couples and houses", "",
           f"{len(results)} run(s). Generated by `experiments/couples.py` on "
           f"{date.today().isoformat()}.", ""]
    for r in results:
        out += [f"## {r['run']}", "",
                f"- proposals: {len(r['proposals'])}, marriages: {r['marriages']}",
                f"- house plots laid out: {len(r['sites_started'])}, houses finished: "
                f"{len(r['houses'])}"]
        if r["fondest_at_last_dawn"]:
            f = r["fondest_at_last_dawn"]
            out.append(f"- fondest eligible pair at the last dawn (day {f['day']}): "
                       f"{f['pair'][0]} and {f['pair'][1]}, affinity {f['pair'][2]}")
        ranks = r["propose_rank_with_sweetheart_near"]
        if ranks:
            out.append("- where family-propose ranked when the sweetheart was near: "
                       + ", ".join(f"{k}: {v}" for k, v in ranks.items()))
        if r["building_at_last_dawn"]:
            b = r["building_at_last_dawn"]
            out.append(f"- at the last dawn a house was needed (day {b['day']}): "
                       f"timber {b['timber']}, work done {b['progress']}, waiting {b['waiting']}")
        out.append("")
        if r["proposals"]:
            out += ["| day | asked by | asked | fondness | answer | home |",
                    "|---|---|---|---|---|---|"]
            for p in r["proposals"]:
                home = p.get("home", "")
                if p.get("waited"):
                    home += " (waiting for a house)"
                out.append(f"| {p['day']} | {p['asker']} | {p['asked']} | {p['affinity']} | "
                           f"{p['answer']} | {home} |")
            out.append("")
        if r["houses"]:
            out += ["| day finished | house | for |", "|---|---|---|"]
            for h in r["houses"]:
                out.append(f"| {h['day']} | {h['place']} | {', '.join(h['couple'] or [])} |")
            out.append("")
        out += ["| instruction | chosen | ranked but refused |", "|---|---|---|"]
        for d in DECISIONS:
            out.append(f"| {d} | {r['chosen'].get(d, 0)} | {r['refused'].get(d, 0)} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    out = RESULTS
    if "--out" in argv:
        i = argv.index("--out")
        out = Path(argv[i + 1]) if Path(argv[i + 1]).is_absolute() else ROOT / argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    if not argv:
        print(__doc__)
        return 2
    results = [analyse(r) for r in argv]
    out.mkdir(parents=True, exist_ok=True)
    (out / "couples.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    text = markdown(results)
    (out / "couples.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
