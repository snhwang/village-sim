#!/usr/bin/env python3
"""What traveling storytellers brought, and what they took away.

    python experiments/visitors.py <run_id> [<run_id> ...]

For each storyteller in each run:

- when it came and went, and its temperament
- the news it carried, and how far each piece spread: how many villagers came
  to hold it, and the longest chain of tellings
- how many conversations it had, and with how many villagers
- how often villagers chose to seek out the stranger, or to keep away
- how many pieces of this village's news it held when it left, or at the
  end of the run if it had not gone

Writes results/visitors.json and .md.
"""

from __future__ import annotations

import collections
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
RESULTS = ROOT / "results"


def day_of(t: int) -> int:
    """The in-game day of a tick: ten-minute ticks, starting at 6am."""
    return (6 * 60 + t * 10) // (24 * 60)


def analyse(run_id: str) -> dict:
    run = RUNS / run_id
    events = [json.loads(line) for line in
              (run / "events.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
    knowledge = json.loads((run / "knowledge.json").read_text(encoding="utf-8"))
    roster = {c["id"]: c for e in events if e["type"] == "roster" for c in e["characters"]}
    visitors = {cid for cid, c in roster.items() if c.get("visitor")}

    arrived = {e["character"]: e for e in events if e["type"] == "visitor_arrived"}
    departed = {e["character"]: e for e in events if e["type"] == "visitor_departed"}
    talks = collections.defaultdict(set)
    count = collections.Counter()
    for e in events:
        if e["type"] == "conversation_start":
            people = set(e.get("participants") or [e.get("a"), e.get("b")])
            for v in people & visitors:
                count[v] += 1
                talks[v] |= people - {v}
    choices = collections.Counter(e.get("chosen") for e in events if e["type"] == "decision"
                                  and (e.get("chosen") or "").startswith("villager-"))

    facts = [f for holder in knowledge.values() for f in holder]
    out = []
    for v in sorted(arrived):
        a = arrived[v]
        tales = sorted({f["root"] for f in facts if f["holder"] == v
                        and f["root"].startswith("tale:")})
        spread = []
        for root in tales:
            tree = [f for f in facts if f["root"] == root]
            holders = {f["holder"] for f in tree} - visitors
            spread.append({"root": root, "text": next(f["text"] for f in tree if f["hop"] == 0),
                           "villagers_holding": len(holders),
                           "longest_chain": max(f["hop"] for f in tree)})
        d = departed.get(v, {})
        # Told to it by villagers: a teller, and not one of its own tales.
        village = {f["root"] for f in facts if f["holder"] == v and f.get("teller")
                   and not f["root"].startswith("tale:")}
        out.append({
            "visitor": v, "name": roster[v]["name"], "temperament": roster[v]["temperament"],
            "arrived": a["t"], "left": d.get("t"), "carried": spread,
            "conversations": count[v], "villagers_talked_with": len(talks[v]),
            "village_news_held": len(village),
        })
    residents = len(set(roster) - visitors)
    return {"run": run_id, "residents": residents, "storytellers": out,
            "villager_choices": dict(choices)}


def markdown(results: list[dict]) -> str:
    lines = ["# Traveling storytellers", "",
             f"{len(results)} run(s). Generated by `experiments/visitors.py` on "
             f"{date.today().isoformat()}.", ""]
    for r in results:
        lines += [f"## {r['run']}", ""]
        if not r["storytellers"]:
            lines += ["No storyteller came.", ""]
        for s in r["storytellers"]:
            day_in = day_of(s["arrived"])
            left = f"day {day_of(s['left'])}" if s["left"] is not None else "still here at the end"
            held = "took away" if s["left"] is not None else "holds"
            lines += [f"**{s['name']}** came on day {day_in} and left {left}. "
                      f"{s['conversations']} conversations with {s['villagers_talked_with']} "
                      f"of {r['residents']} villagers. It {held} {s['village_news_held']} "
                      f"{'piece' if s['village_news_held'] == 1 else 'pieces'} of this "
                      f"village's news.", "",
                      "| news carried | villagers holding it | longest chain |", "|---|---|---|"]
            for c in s["carried"]:
                lines.append(f"| {c['text']} | {c['villagers_holding']} | {c['longest_chain']} |")
            lines.append("")
        lines += [f"Villagers' choices toward strangers: {r['villager_choices'] or 'none'}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    results = [analyse(r) for r in argv]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "visitors.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    text = markdown(results)
    (RESULTS / "visitors.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
