#!/usr/bin/env python3
"""School, graduation, trades and masters, as they happened in some runs.

    python experiments/trades.py <run_id> [<run_id> ...]

Needs runs with growth on, the default (not --no-growth). Reports:

- who graduated from school, and on which day
- how each graduate chose a trade: the trade instructions it ranked, their
  scores, what was refused, and what it chose
- who took whom on as master, and how fond of the master the graduate was
- who qualified in a trade and became an adult
- how often children went to school and elders taught there
- what held villagers back from growing up, by requirement

Writes results/trades.json and .md, or into another directory given
with --out, for runs that are not the paper's.
"""

from __future__ import annotations

import collections
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
RESULTS = ROOT / "results"


def day_of(t: int) -> int:
    return (6 * 60 + t * 10) // (24 * 60)


def analyse(run_id: str) -> dict:
    run = RUNS / run_id
    meta = json.loads((run / "meta.json").read_text(encoding="utf-8"))
    roster, graduated, choices, apprenticed, qualified = {}, [], [], [], []
    school = collections.Counter()
    held = collections.Counter()
    with open(run / "events.jsonl", encoding="utf-8") as f:
        for line in f:
            e = json.loads(line)
            kind = e["type"]
            if kind == "roster":
                roster.update({c["id"]: c for c in e["characters"]})
            elif kind == "stage_change" and e["was"] == "child":
                graduated.append({"who": e["character"], "day": day_of(e["t"])})
            elif kind == "decision" and "graduating" in (e.get("tags") or []):
                ranked = [r for r in e.get("retrieved", []) if isinstance(r, dict)
                          and r["id"].startswith("trade-")]
                choices.append({
                    "who": e["character"], "day": day_of(e["t"]), "chosen": e.get("chosen"),
                    "temperament": roster.get(e["character"], {}).get("temperament"),
                    "leanings": [t for t in e["tags"]
                                 if t.startswith(("parent_", "needed_", "skill_"))],
                    "ranked": [(r["id"], r.get("score")) for r in ranked],
                    "refused": [r for r in (e.get("refused") or []) if r.startswith("trade-")]})
            elif kind == "apprenticed":
                apprenticed.append({"who": e["character"], "trade": e["trade"],
                                    "master": e["master"], "day": day_of(e["t"]),
                                    "fondness": e.get("fondness"),
                                    "master_is_parent": e["master"] in
                                    roster.get(e["character"], {}).get("parents", [])})
            elif kind == "took_up_trade":
                qualified.append({"who": e["character"], "trade": e["trade"],
                                  "master": e["master"], "day": day_of(e["t"])})
            elif kind == "decision" and e.get("chosen") in ("child-school", "elder-teach"):
                school[e["chosen"]] += 1
            elif kind == "growth_held_back":
                for reason in e.get("missing", []):
                    held[(e["stage"], reason.split(" ")[0].rstrip(":"))] += 1
    return {"run": run_id, "growth": (meta.get("config") or {}).get("growth"),
            "graduated": graduated, "choices": choices, "apprenticed": apprenticed,
            "qualified": qualified, "school": dict(school),
            "held_back": {f"{s}: {r}": n for (s, r), n in held.most_common()}}


def markdown(results: list[dict]) -> str:
    out = ["# School and trades", "",
           f"{len(results)} run(s). Generated by `experiments/trades.py` on "
           f"{date.today().isoformat()}.", ""]
    for r in results:
        out += [f"## {r['run']}", ""]
        if not r["growth"]:
            out += ["Growth was off (--no-growth), so nobody could grow up.", ""]
        out.append(f"- school: {r['school'] or 'nobody went'}")
        for g in r["graduated"]:
            out.append(f"- {g['who']} graduated on day {g['day']}")
        for c in r["choices"]:
            ranked = ", ".join(f"{t.removeprefix('trade-')} {s}" for t, s in c["ranked"][:4])
            out.append(f"- {c['who']} chose {c['chosen']} on day {c['day']}, leaning "
                       f"{c['leanings']}. Ranked: {ranked}. Refused: {c['refused'] or 'none'}")
        for a in r["apprenticed"]:
            parent = ", a parent" if a["master_is_parent"] else ""
            fond = f" (fondness {a['fondness']})" if a.get("fondness") is not None else ""
            out.append(f"- {a['who']} was taken on as a {a['trade']} by {a['master']}{parent}{fond}")
        for q in r["qualified"]:
            out.append(f"- {q['who']} qualified as a {q['trade']} on day {q['day']}, "
                       f"under {q['master']}")
        out.append(f"- held back, by requirement (villager-days): {r['held_back'] or 'none'}")
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    out = RESULTS
    if "--out" in argv:
        i = argv.index("--out")
        out = Path(argv[i + 1]) if Path(argv[i + 1]).is_absolute() else ROOT / argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    if not argv:
        print(__doc__)
        return 2
    results = [analyse(r) for r in argv]
    out.mkdir(parents=True, exist_ok=True)
    (out / "trades.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    text = markdown(results)
    (out / "trades.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
