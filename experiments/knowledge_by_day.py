#!/usr/bin/env python3
"""Does what villagers can do grow as they learn? Day by day, the share of
decisions taken on instructions only knowledge made reachable.

    python experiments/knowledge_by_day.py [<run_id> ...] [--out results/]

With no run ids it reads the paper's six runs (results/paper_runs.txt). An
instruction counts when knowledge gates it, as in experiments/knowledge_flow.py.
Day 0 is left out, since nobody knows anything yet, and so is a last day that
holds only a run's closing ticks.

Reports the share pooled by day, and per run the share on its first three
full days against its last three, with how many runs rose. Until 2026-10-19
the last three were fixed at days 7 to 9, the end of a ten-day run, which in
a forty-day run are early days.

Writes knowledge_by_day.json and .md in results/, or in --out.
"""

from __future__ import annotations

import collections
import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from knowledge_flow import knowledge_gated  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
RESULTS = ROOT / "results"
FIRST_DAYS = LAST_DAYS = 3
MIN_DECISIONS_A_DAY = 100      # fewer, and the day is only a run's closing ticks


def day_of(t: int) -> int:
    return (6 * 60 + t * 10) // (24 * 60)


def per_day(run_id: str, gated: set[str]) -> dict[int, list[int]]:
    days: dict[int, list[int]] = collections.defaultdict(lambda: [0, 0])
    with open(RUNS / run_id / "events.jsonl", encoding="utf-8") as f:
        for line in f:
            if '"decision"' not in line:
                continue
            e = json.loads(line)
            if e.get("type") != "decision" or e.get("character") == "world":
                continue
            day = days[day_of(e["t"])]
            day[1] += 1
            day[0] += e.get("chosen") in gated
    return {d: v for d, v in days.items() if d > 0 and v[1] >= MIN_DECISIONS_A_DAY}


def share(counts: list[list[int]]) -> float:
    k, n = sum(c[0] for c in counts), sum(c[1] for c in counts)
    return round(100 * k / n, 1) if n else 0.0


def main(argv: list[str]) -> int:
    out_dir = RESULTS
    if "--out" in argv:
        i = argv.index("--out")
        out_dir = Path(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
    runs = argv or (RESULTS / "paper_runs.txt").read_text(encoding="utf-8").split()
    gated = knowledge_gated()
    by_run = {r: per_day(r, gated) for r in runs}
    pooled: dict[int, list[list[int]]] = collections.defaultdict(list)
    for days in by_run.values():
        for d, counts in days.items():
            pooled[d].append(counts)
    rows = [{"day": d, "share_pct": share(pooled[d]),
             "knowledge_only": sum(c[0] for c in pooled[d]),
             "decisions": sum(c[1] for c in pooled[d])} for d in sorted(pooled)]
    runs_out = []
    for r, days in by_run.items():
        full = sorted(days)
        first, last = full[:FIRST_DAYS], full[-LAST_DAYS:]
        early = share([days[d] for d in first])
        late = share([days[d] for d in last])
        runs_out.append({"run": r, "first_days": first, "last_days": last,
                         "first_days_pct": early, "last_days_pct": late,
                         "rose": late > early})
    result = {"runs": runs, "by_day": rows, "by_run": runs_out,
              "runs_that_rose": sum(r["rose"] for r in runs_out)}
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "knowledge_by_day.json").write_text(json.dumps(result, indent=2),
                                                   encoding="utf-8")
    out = ["# What knowledge makes reachable, day by day", "",
           f"{len(runs)} run(s). Generated by `experiments/knowledge_by_day.py` on "
           f"{date.today().isoformat()}.", "",
           "| day | knowledge-only decisions | decisions | share |", "|---|---|---|---|"]
    out += [f"| {r['day']} | {r['knowledge_only']:,} | {r['decisions']:,} | {r['share_pct']}% |"
            for r in rows]
    out += ["", "| run | first three days | last three days | rose |", "|---|---|---|---|"]
    out += [f"| {r['run']} | days {r['first_days'][0]} to {r['first_days'][-1]}: "
            f"{r['first_days_pct']}% | days {r['last_days'][0]} to {r['last_days'][-1]}: "
            f"{r['last_days_pct']}% | {'yes' if r['rose'] else 'no'} |" for r in runs_out]
    out += ["", f"It rose in {result['runs_that_rose']} of {len(runs_out)} runs."]
    text = "\n".join(out) + "\n"
    (out_dir / "knowledge_by_day.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
