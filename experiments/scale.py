#!/usr/bin/env python3
"""A larger village: does the arrangement run at ten times the size?

    python experiments/scale.py <run_dir> [<run_dir> ...]

The runs are made on the paper's build (commit 19611f5), with a village
generated by experiments/make_village.py, so the system is the one the paper
measures and only the population differs. README.md, "A larger village", has
the commands.

For each run it reports the size, how long it took, the model and embedding
calls, the decisions and conversations, and how far news reached, measured
the way experiments/knowledge_flow.py measures the paper's runs. A run
directory can be anywhere, since these runs are made in another checkout.

Writes results/scale.json and .md.
"""

from __future__ import annotations

import json
import sys
from datetime import date, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from knowledge_flow import analyse, load  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
TICKS_PER_DAY = 144


def find(run: str) -> Path:
    path = Path(run)
    if path.is_dir():
        return path.resolve()
    for base in (ROOT / "runs", ROOT.parent / "hearthwick-paper-build" / "runs"):
        if (base / run).is_dir():
            return base / run
    raise SystemExit(f"no run directory {run}")


def summarise(run_dir: Path) -> dict:
    run = load(run_dir)
    meta = run["meta"]
    events = run["events"]
    started = datetime.fromisoformat(meta["started"])
    finished = datetime.fromisoformat(meta["finished"]) if meta.get("finished") else None
    resumed = sum(1 for e in events if e["type"] == "resumed")
    reach = analyse([run], embedder=None)["reach"]
    embedder = meta.get("embedder") or {}
    return {
        "run": run_dir.name,
        "village": meta.get("village"),
        "villagers": meta.get("villagers"),
        "days": round((meta.get("ticks") or 0) / TICKS_PER_DAY, 2),
        "hearthwick": (meta.get("code") or {}).get("hearthwick"),
        "speech_model": (meta.get("speech_model") or {}).get("model"),
        "seconds": round((finished - started).total_seconds()) if finished else None,
        # Wall clock from start to finish counts any time the run was stopped.
        "resumed": resumed,
        "speech_calls": meta.get("speech_calls"),
        "speech_failures": meta.get("speech_failures"),
        "embedding_calls": embedder.get("calls"),
        "embedding_cache_hits": embedder.get("cache_hits"),
        "decisions": sum(1 for e in events
                         if e["type"] == "decision" and e.get("character") != "world"),
        "conversations": sum(1 for e in events if e["type"] == "conversation_start"),
        "events_that_spread": reach["events_that_spread"],
        "median_holders": reach["median_holders"],
        "median_share_pct": reach["median_share_pct"],
        "median_wordings": reach.get("median_wordings"),
        "deepest_chain": reach.get("deepest_chain"),
    }


def markdown(rows: list[dict]) -> str:
    out = ["# A larger village", "",
           f"Generated by `experiments/scale.py` on {date.today().isoformat()}.", "",
           "| run | villagers | days | wall clock | speech calls (failed) | embedding calls "
           "(cached) | decisions | conversations | events that spread | median holders "
           "| median wordings | longest chain |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        clock = f"{r['seconds'] / 60:.0f} min" if r["seconds"] is not None else "unfinished"
        if r["resumed"]:
            clock += f", resumed {r['resumed']}x"
        out.append(
            f"| {r['run']} | {r['villagers']} | {r['days']} | {clock} | "
            f"{r['speech_calls']:,} ({r['speech_failures']}) | "
            f"{r['embedding_calls']:,} ({r['embedding_cache_hits']:,}) | "
            f"{r['decisions']:,} | {r['conversations']:,} | {r['events_that_spread']} | "
            f"{r['median_holders']} of {r['villagers']} | {r['median_wordings']} | "
            f"{r['deepest_chain']} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    rows = [summarise(find(r)) for r in argv]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "scale.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    text = markdown(rows)
    (RESULTS / "scale.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
