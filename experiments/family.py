#!/usr/bin/env python3
"""Births: who had children, when, and how the village grew.

    python experiments/family.py <run_id> [<run_id> ...]

For each run:

- every birth, with its day, parents, and the temperament the child expresses
- how often a couple chose to have a child, and how often the choice ranked
  but was refused (by age, not being home together, a low granary, a full
  house, or too soon after the last)
- the village by stage at the start and at the end

Writes results/family.json and .md, or into another directory given
with --out, for runs that are not the paper's.
"""

from __future__ import annotations

import collections
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
RESULTS = ROOT / "results"
DECISION = "family-have-child"


def day_of(t: int) -> int:
    return (6 * 60 + t * 10) // (24 * 60)


def analyse(run_id: str) -> dict:
    run = RUNS / run_id
    births, chosen, refused, tries, conceived = [], 0, 0, 0, 0
    first_roster, roster = None, {}
    with open(run / "events.jsonl", encoding="utf-8") as f:
        for line in f:
            e = json.loads(line)
            kind = e["type"]
            if kind == "roster":
                if first_roster is None:
                    first_roster = {c["id"]: c for c in e["characters"]}
                roster.update({c["id"]: c for c in e["characters"]})
            elif kind == "tried_for_child":
                tries += 1
                conceived += bool(e.get("conceived"))
            elif kind == "born":
                births.append({"day": day_of(e["t"]), "child": e["character"],
                               "mother": e["mother"], "father": e["father"],
                               "home": e["home"], "temperament": e["temperament"]})
            elif kind == "decision" and e.get("character") != "world":
                if e.get("chosen") == DECISION:
                    chosen += 1
                elif DECISION in (e.get("refused") or []):
                    refused += 1
    last = None
    with open(run / "frames.jsonl", encoding="utf-8") as f:
        for line in f:
            last = line
    end_stage = collections.Counter(row[4] for row in json.loads(last)["c"]) if last else {}
    start_stage = collections.Counter(c["stage"] for c in (first_roster or {}).values())
    return {"run": run_id, "births": births, "decision_chosen": chosen,
            "tries": tries, "conceived": conceived,
            "decision_refused": refused, "start": dict(start_stage), "end": dict(end_stage)}


def markdown(results: list[dict]) -> str:
    out = ["# Births", "", f"{len(results)} run(s). Generated by `experiments/family.py` on "
           f"{date.today().isoformat()}.", ""]
    for r in results:
        out += [f"## {r['run']}", "",
                f"- births: {len(r['births'])}",
                f"- a couple chose to have a child {r['decision_chosen']} times, and the choice "
                f"ranked but was refused {r['decision_refused']} times",
                f"- couples tried {r['tries']} times, and {r['conceived']} tries gave a child",
                f"- at the start: {r['start']}",
                f"- at the end: {r['end']}", ""]
        if r["births"]:
            out += ["| day | child | mother | father | home | expresses |", "|---|---|---|---|---|---|"]
            for b in r["births"]:
                t = b["temperament"]
                out.append(f"| {b['day']} | {b['child']} | {b['mother']} | {b['father']} | "
                           f"{b['home']} | {', '.join(t[k] for k in sorted(t))} |")
            out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    out = RESULTS
    if "--out" in argv:
        i = argv.index("--out")
        out = Path(argv[i + 1]) if Path(argv[i + 1]).is_absolute() else ROOT / argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    if not argv:
        print(__doc__)
        return 2
    results = [analyse(r) for r in argv]
    out.mkdir(parents=True, exist_ok=True)
    (out / "family.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    text = markdown(results)
    (out / "family.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
